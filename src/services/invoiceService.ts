/**
 * POST /api/Invoice
 * Creates an electronic invoice tied to a debt or payment.
 */
export async function createInvoice(
  command: CreateInvoiceCommand
): Promise<CreateInvoiceResponseDto> {
  return httpClient.post<CreateInvoiceResponseDto>('/Invoice', command);
}

/**
 * GET /api/Invoice/{id}/pdf
 * Fetches the official PDF binary stream generated by the server.
 * Defaults to 15 if no ID provided.
 */
export async function getInvoicePdfBlob(invoiceId: number | string = 15): Promise<Blob> {
  const cleanId = String(invoiceId).replace(/[^0-9]/g, '') || '15';
  return httpClient.getBlob(`/Invoice/${cleanId}/pdf`);
}

/**
 * GET https://whateq.runasp.net/api/Invoice/15/pdf
 * Explicit helper to fetch invoice 15 PDF directly as requested.
 */
export async function getInvoice15PdfBlob(): Promise<Blob> {
  return getInvoicePdfBlob(15);
}

/**
 * Returns the direct absolute API URL for the PDF (e.g. https://whateq.runasp.net/api/Invoice/15/pdf).
 */
export function getInvoicePdfDirectUrl(invoiceId: number | string = 15): string {
  const cleanId = String(invoiceId).replace(/[^0-9]/g, '') || '15';
  return `https://whateq.runasp.net/api/Invoice/${cleanId}/pdf`;
}

/**
 * Downloads the PDF blob locally via browser save dialog/link.
 */
export function triggerPdfDownload(blob: Blob, filename = 'watheq_invoice.pdf'): void {
  const url = window.URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  window.URL.revokeObjectURL(url);
}


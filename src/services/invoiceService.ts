/**
 * Converts API errors into clean, user-facing Arabic messages.
 */
export function toInvoiceErrorMessage(error: unknown): string {
  if (error instanceof ApiError) {
    const body = error.body as {
      result?: { code?: number; message?: string };
      message?: string;
      errors?: Record<string, string[]>;
    } | null;

    if (body?.result?.message) {
      return body.result.message;
    }
    if (body?.message) {
      return body.message;
    }
    if (body?.errors) {
      const first = Object.values(body.errors).flat()[0];
      if (first) return first;
    }

    if (error.status === 404) {
      return 'الفاتورة المحددة غير موجودة في سجلات الخادم (The specified invoice does not exist).';
    }
    if (error.status === 400) {
      return 'بيانات الفاتورة غير صحيحة، يرجى مراجعة المدخلات.';
    }
    if (error.status === 401) {
      return 'انتهت جلستك، يرجى إعادة تسجيل الدخول.';
    }
    if (error.status === 500) {
      return 'حدث خطأ في خادم الفواتير، يرجى المحاولة لاحقاً.';
    }
  }
  return 'تعذر الاتصال بخادم الفواتير، يرجى التحقق من اتصال الإنترنت.';
}

function unwrapEnvelope(raw: unknown): unknown {
  if (raw && typeof raw === 'object' && !Array.isArray(raw)) {
    const r = raw as Record<string, unknown>;
    if ('data' in r && r.data !== undefined && r.data !== null) return unwrapEnvelope(r.data);
    if ('Data' in r && r.Data !== undefined && r.Data !== null) return unwrapEnvelope(r.Data);
  }
  return raw;
}

